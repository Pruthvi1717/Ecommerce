ALTER TABLE orders MODIFY COLUMN order_status VARCHAR(32) NULL;

UPDATE orders
SET order_status = CASE order_status
    WHEN '0' THEN 'PENDING'
    WHEN '1' THEN 'SHIPPED'
    WHEN '2' THEN 'DELIVERED'
    WHEN '3' THEN 'CANCELED'
    ELSE 'PENDING'
END;

ALTER TABLE orders MODIFY COLUMN order_status VARCHAR(32) NOT NULL DEFAULT 'PENDING';